#!/usr/bin/env python3
"""Write the Mathlib-side glue of the K7 proof (kernel only, half domain): Bohr59aK7G/Gjj.lean (32 modules: the cell
property of root cells 64 j .. 64 j + 63, light cells from cellw7_i / cellv7_i of Bohr59aK7C/Ciiii via
Bohr59aSplitK.cellOK_of_KC7, the split cells from tools/gen_k7split.py), Bohr59aK7G/Final.lean (sidon7K : S_7 <= 2.552,
kernel only) and Bohr59aK7G/Headline.lean (with sidon5K, sidon6K of the K5/K6 packages: K2_ge_K7, K_2 >= 0.301665).
Cell theorem names assumed: cellw7_<i> : walkKC tree7_<i> (rootMsH 5 <i>) (List.replicate 6 2) cls7_<i> = some [],
cellv7_<i> : allP (allP PF7C) cls7_<i>; split cells: HEAVY[i] = (module, theorem : CellOKH 5 B i), from the plan of
tools/k7_split_plan.py (cells with more than 64 leaves; tools/gen_k7split.py SHARD OUT HELPER NPROC H<sss> CELLS --vmap MAP).
usage: gen_k7_final.py OUT_DIR SPLIT_PLAN"""
import json, os, sys
out, plan = sys.argv[1], json.load(open(sys.argv[2]))
NC, PER = 2048, 64
NM = NC // PER
HEAVY = {int(i): tuple(v) for i, v in plan['heavy'].items()}
if len(HEAVY) + len(plan['direct']) != NC or set(HEAVY) & set(plan['direct']):
    sys.exit('GEN FAILED: the split plan does not partition the root cells')
B = '((2552 : ℕ) : ℝ) / ((1000 : ℕ) : ℝ)'
os.makedirs(os.path.join(out, 'Bohr59aK7G'), exist_ok=True)
for j in range(NM):
    lo, hi = PER * j, PER * j + PER
    imps = ['import Bohr59aSplitK.CodeWalkSound\n']
    for i in range(lo, hi):
        imps.append('import %s\n' % (HEAVY[i][0] if i in HEAVY else 'Bohr59aK7C.C%04d' % i))
    lines = imps + [f'\n/-! Glue: the cell property of the root cells {lo}..{hi - 1} (generated by tools/gen_k7_final.py). -/\n\n',
                    'open Bohr59a.CertK Bohr59a.Cert Bohr59aK Bohr59aCore Bohr59aSplitK\n', 'set_option maxHeartbeats 0\n\n',
                    'namespace Bohr59aK7G\n\n',
                    f'theorem cells7_{j} : ∀ i, {lo} ≤ i → i < {hi} → CellOKH 5 ({B}) i := by\n',
                    '  intro i h1 h2\n', '  interval_cases i\n']
    for i in range(lo, hi):
        lines.append('  · exact %s\n' % (HEAVY[i][1] if i in HEAVY else f'cellOK_of_KC7 cellw7_{i} cellv7_{i}'))
    lines.append('\nend Bohr59aK7G\n')
    open(os.path.join(out, 'Bohr59aK7G', f'G{j:02d}.lean'), 'w').write(''.join(lines))
fin = [f'import Bohr59aK7G.G{j:02d}\n' for j in range(NM)] + ['import Bohr59a.CertHalf\n\n']
fin += ['/-!\n# `S({0..7}) ≤ 2.552`, K version (kernel only)\n\n',
        'From the kernel checks of the k = 7 half-domain certificate (keys as codes, packed hints, global vertex layer):\n',
        'every root cell of `[0, 1] × [-1, 1]^5` has the cell property, then `Bohr59a.Cert.sidon_of_cells_half` (conjugation\n',
        'covers the other half).  Generated by tools/gen_k7_final.py.\n-/\n\n',
        'open Bohr59a Bohr59a.Cert Bohr59aCore\n', 'set_option maxHeartbeats 0\n\n', 'namespace Bohr59aK\n\n',
        f'theorem cells7_all : ∀ i < 2 * 4 ^ 5, CellOKH 5 ({B}) i := by\n', '  intro i hi\n',
        '  have hi\' : i < 2048 := by simpa using hi\n',
        f'  obtain ⟨j, r, hr, rfl⟩ : ∃ j r, r < {PER} ∧ i = {PER} * j + r := ⟨i / {PER}, i % {PER}, Nat.mod_lt _ (by norm_num),\n',
        f'    (Nat.div_add_mod i {PER}).symm⟩\n', f'  have hj : j < {NM} := by omega\n', '  interval_cases j\n']
fin += [f'  · exact Bohr59aK7G.cells7_{j} _ (by omega) (by omega)\n' for j in range(NM)]
fin += ['\n/-- `S({0..7}) ≤ 2.552`, kernel only -/\n',
        'theorem sidon7K : SidonBound 7 (2552 / 1000) := by\n',
        f'  have h : SidonBound (5 + 1 + 1) ({B}) := sidon_of_cells_half cells7_all\n',
        '  norm_num at h ⊢\n', '  exact h\n\n', 'end Bohr59aK\n']
open(os.path.join(out, 'Bohr59aK7G', 'Final.lean'), 'w').write(''.join(fin))
head = ['import Bohr59aK7G.Final\n', 'import Bohr59aK6G.Final\n', 'import Bohr59a.FinalV3b\n\n',
        '/-!\n# `K₂ ≥ 0.301665`, K version (kernel only)\n\n',
        '`sidon5K`, `sidon6K` (K5, K6 packages), `sidon7K` (`Bohr59aK7G/Final.lean`), then `Bohr59a.K2_ge_of_sidon7`.\n',
        'Generated by tools/gen_k7_final.py.\n-/\n\n', 'open Bohr59a\n\n', 'namespace Bohr59aK\n\n',
        '/-- **`K₂ ≥ 0.301665`** (kernel only), given Patel\'s colligation estimate. -/\n',
        'theorem K2_ge_K7 (hPC : PatelColligation) : (60333 / 200000 : ℝ) ≤ K2 :=\n',
        '  K2_ge_of_sidon7 hPC sidon5K sidon6K sidon7K\n\n', 'end Bohr59aK\n']
open(os.path.join(out, 'Bohr59aK7G', 'Headline.lean'), 'w').write(''.join(head))
print('wrote', NM, 'glue modules + Final + Headline')
