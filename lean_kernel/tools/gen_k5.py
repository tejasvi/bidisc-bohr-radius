#!/usr/bin/env python3
"""Generate the kernel-only (track K) modules of S({0..5}) <= 2187/1000 from the frozen bb5_t2187.json.

* Vertex modules Bohr59aK5V/V000 ... : one theorem per vertex certificate (JSON order, PER_V per module)
      theorem v_<idx> : vertexOKK trigTT 5 2187 1000 [key] [Y] = true := by decide +kernel
  key: ['c', q] -> <false, 512 q, 0>, ['t', q, h] -> <true, 512 q, log2(1/h)>;
  Y: the 5 complex numbers y_1..y_5 as Gaussian integers (2^128 re, 2^128 im), exact (refused if not integral).
* Chunk modules Bohr59aK5C/P000 ... : the leaf keys of every root cell i (walkK order, 3^4 = 81 per leaf) in chunks of
  CHUNK keys; per chunk k
      def kl_<i>_<k> : List (List Comp) := [...]
      theorem cellv_<i>_<k> : allP (fun key => ∃ Y, vertexOKK trigTT 5 2187 1000 key Y = true) kl_<i>_<k> :=
        ⟨⟨_, v_a⟩, ⟨_, v_b⟩, ..., trivial⟩
  (one linking declaration per chunk: the kernel time of a linking declaration grows quadratically with the number of
  distinct vertex theorems it uses), packed in order into modules of at most PBUDGET keys.
* Cell modules Bohr59aK5C/C00 ... : PER_C root cells each; per root cell i
      def tree_<i> : Tree := ...
      def kl_<i> : List (List Comp) := kl_<i>_0 ++ (kl_<i>_1 ++ (... ++ kl_<i>_<m>))
      theorem cellw_<i> : walkK tree_<i> (rootMs 4 <i>) (List.replicate 4 3) kl_<i> = some [] := by decide +kernel
      theorem cellv_<i> : allP (fun key => ∃ Y, vertexOKK trigTT 5 2187 1000 key Y = true) kl_<i> :=
        allP_app cellv_<i>_0 (allP_app cellv_<i>_1 (... cellv_<i>_<m>))
  importing the chunk modules of its cells; allP_app (allP of a concatenation) is in Bohr59aK5C/Help.lean (core Lean).
  Key literals are printed by one function everywhere.

usage: gen_k5.py FROZEN_DIR OUT_DIR [PER_V=1000] [PER_C=64] [CHUNK=64] [PBUDGET=4000]
writes OUT_DIR/Bohr59aK5V/*.lean, OUT_DIR/Bohr59aK5C/*.lean and OUT_DIR/stats/K5K.json
(v2, 2026-10-21: chunked linking; the vertex modules are byte-identical to v1)
"""
import hashlib, itertools, json, os, sys
from fractions import Fraction

if sys.flags.optimize:
    sys.exit('refusing to run with python -O')

K, N0, D, BNUM, BDEN = 5, 8, 4, 2187, 1000
SCALE = 2 ** 128
PRED = '(fun key => ∃ Y, vertexOKK trigTT %d %d %d key Y = true)' % (K, BNUM, BDEN)
HELP = ('''import Bohr59aCoreK.Walk

/-! `allP` of a concatenation, for the chunked key lists of the K5 cell modules (generated by tools/gen_k5.py). -/

namespace Bohr59aK5H

open Bohr59aK

theorem allP_app {α : Type} {P : α → Prop} : ∀ {l₁ l₂ : List α}, allP P l₁ → allP P l₂ → allP P (l₁ ++ l₂)
  | [], _, _, h₂ => h₂
  | _ :: l, _, h₁, h₂ => ⟨h₁.1, allP_app (l₁ := l) h₁.2 h₂⟩

end Bohr59aK5H
''')
OPTS = 'set_option maxRecDepth 100000\nset_option maxHeartbeats 0\nset_option Elab.async false\n\n'
HEADER_V = ('import Bohr59aCoreK.TrigTab\nopen Bohr59aK Bohr59aCore\nset_option maxRecDepth 100000\n'
            'set_option maxHeartbeats 0\nset_option Elab.async false\n\n')


def die(msg):
    sys.exit('GEN FAILED: ' + msg)


def comp_of_json(kk):
    if isinstance(kk, list) and len(kk) == 2 and kk[0] == 'c':
        m = Fraction(kk[1]) * 512
        if m.denominator != 1:
            die('corner not a multiple of 1/512: %s' % kk)
        return (False, m.numerator, 0)
    if isinstance(kk, list) and len(kk) == 3 and kk[0] == 't':
        m, h = Fraction(kk[1]) * 512, Fraction(kk[2])
        if m.denominator != 1 or h.numerator != 1 or h.denominator & (h.denominator - 1) or not (0 < h <= Fraction(1, 4)):
            die('bad tangent key %s' % kk)
        return (True, m.numerator, h.denominator.bit_length() - 1)
    die('bad key component %s' % kk)


def fmt_comp(c):
    return '⟨%s, %d, %d⟩' % ('true' if c[0] else 'false', c[1], c[2])


def fmt_key(key):
    return '[' + ', '.join(fmt_comp(c) for c in key) + ']'


def gi_of(x_re, x_im):
    a, b = Fraction(x_re) * SCALE, Fraction(x_im) * SCALE
    if a.denominator != 1 or b.denominator != 1:
        die('y not a dyadic with denominator <= 2^128')
    return '⟨%d, %d⟩' % (a.numerator, b.numerator)


def opts(m, j):
    return [(False, m - 2 ** (9 - j), 0), (False, m + 2 ** (9 - j), 0), (True, m, j)]


def leaf_keys(ms, js):
    if not all(2 <= j <= 9 for j in js):
        die('leaf half-width exponent out of [2, 9]')
    return [list(t) for t in itertools.product(*[opts(m, j) for m, j in zip(ms, js)])]


def walk(node, ms, js, out, depth=0):
    """leaf keys in walkK order (lo subtree before hi)"""
    if depth > 400:
        die('tree too deep')
    if node == 'L':
        out.extend(leaf_keys(ms, js))
        return
    if not (isinstance(node, list) and len(node) == 4 and node[0] == 'S' and isinstance(node[1], int) and 0 <= node[1] < D):
        die('bad node')
    d = node[1]
    if js[d] > 8:
        die('split below half-width 2^-9')
    step = 2 ** (8 - js[d])
    lo_ms = list(ms); lo_ms[d] -= step
    hi_ms = list(ms); hi_ms[d] += step
    js2 = list(js); js2[d] += 1
    walk(node[2], lo_ms, js2, out, depth + 1)
    walk(node[3], hi_ms, js2, out, depth + 1)


def fmt_tree(node):
    if node == 'L':
        return '.leaf'
    return '(.split %d %s %s)' % (node[1], fmt_tree(node[2]), fmt_tree(node[3]))


def root_ms(i):
    digits = []
    for _ in range(D):
        digits.append(i % N0); i //= N0
    digits.reverse()
    return [-512 + (2 * a + 1) * 64 for a in digits]


def main():
    frozen, out = sys.argv[1], sys.argv[2]
    per_v = int(sys.argv[3]) if len(sys.argv) > 3 else 1000
    per_c = int(sys.argv[4]) if len(sys.argv) > 4 else 64
    chunk = int(sys.argv[5]) if len(sys.argv) > 5 else 64
    pbudget = int(sys.argv[6]) if len(sys.argv) > 6 else 4000
    cert = json.load(open(os.path.join(frozen, 'bb5_t2187.json')))
    if not (cert['k'] == K and cert['n0'] == N0 and len(cert['tree']) == N0 ** D):
        die('unexpected header')
    verts = cert['verts']
    index = {}
    vdir = os.path.join(out, 'Bohr59aK5V'); os.makedirs(vdir, exist_ok=True)
    cdir = os.path.join(out, 'Bohr59aK5C'); os.makedirs(cdir, exist_ok=True)
    os.makedirs(os.path.join(out, 'stats'), exist_ok=True)
    nvmod = (len(verts) + per_v - 1) // per_v
    width_v = max(3, len(str(nvmod - 1)))
    vmods = []
    for mi in range(nvmod):
        name = 'V%0*d' % (width_v, mi)
        lines = [HEADER_V]
        for idx in range(mi * per_v, min(len(verts), (mi + 1) * per_v)):
            ent = verts[idx]
            if not (isinstance(ent, list) and len(ent) == 2 and len(ent[0]) == D and len(ent[1]) == 2 * K):
                die('bad vertex entry %d' % idx)
            key = tuple(comp_of_json(kk) for kk in ent[0])
            if key in index:
                die('duplicate key %s' % (key,))
            index[key] = (idx, name)
            ys = ', '.join(gi_of(ent[1][2 * j], ent[1][2 * j + 1]) for j in range(K))
            lines.append('theorem v_%d : vertexOKK trigTT %d %d %d %s [%s] = true := by decide +kernel\n'
                         % (idx, K, BNUM, BDEN, fmt_key(key), ys))
        path = os.path.join(vdir, name + '.lean')
        open(path + '.part', 'w').write(''.join(lines)); os.replace(path + '.part', path)
        vmods.append(name)
    tree = cert['tree']
    # leaf keys and vertex references of every root cell, in chunks of `chunk` keys
    cells = []
    used_total = 0
    for i in range(len(tree)):
        kl = []
        walk(tree[i], root_ms(i), [3] * D, kl)
        refs = []
        for key in kl:
            t = tuple(tuple(c) for c in key)
            if t not in index:
                die('root cell %d: missing vertex certificate %s' % (i, t))
            refs.append(index[t])
        used_total += len(kl)
        cells.append([(kl[a:a + chunk], refs[a:a + chunk]) for a in range(0, len(kl), chunk)])
    # pack the chunks, in order, into chunk modules of at most `pbudget` keys
    pmods, cur, cur_n = [], [], 0
    for i, chs in enumerate(cells):
        for k, (kl, refs) in enumerate(chs):
            if cur and cur_n + len(kl) > pbudget:
                pmods.append(cur); cur, cur_n = [], 0
            cur.append((i, k, kl, refs)); cur_n += len(kl)
    if cur:
        pmods.append(cur)
    width_p = max(3, len(str(len(pmods) - 1)))
    where = {}
    pstats = []
    for pi, items in enumerate(pmods):
        name = 'P%0*d' % (width_p, pi)
        need, body = set(), []
        for i, k, kl, refs in items:
            where[(i, k)] = name
            need.update(vm for _, vm in refs)
            body.append('def kl_%d_%d : List (List Comp) := [%s]\n' % (i, k, ', '.join(fmt_key(x) for x in kl)))
            body.append('theorem cellv_%d_%d : allP %s kl_%d_%d :=\n  ⟨%s⟩\n\n'
                        % (i, k, PRED, i, k, ', '.join(['⟨_, v_%d⟩' % r for r, _ in refs] + ['trivial'])))
        head = ['import Bohr59aCoreK.Walk\n'] + ['import Bohr59aK5V.%s\n' % m for m in sorted(need)]
        head.append('open Bohr59aK Bohr59aCore\n' + OPTS)
        path = os.path.join(cdir, name + '.lean')
        open(path + '.part', 'w').write(''.join(head + body)); os.replace(path + '.part', path)
        pstats.append(dict(module=name, chunks=len(items), keys=sum(len(x[2]) for x in items), imports=len(need)))
    hpath = os.path.join(cdir, 'Help.lean')
    open(hpath + '.part', 'w').write(HELP); os.replace(hpath + '.part', hpath)
    ncmod = (len(tree) + per_c - 1) // per_c
    width_c = max(2, len(str(ncmod - 1)))
    cstats = []
    for ci in range(ncmod):
        name = 'C%0*d' % (width_c, ci)
        body, need = [], set()
        for i in range(ci * per_c, min(len(tree), (ci + 1) * per_c)):
            m = len(cells[i])
            need.update(where[(i, k)] for k in range(m))
            body.append('def tree_%d : Tree := %s\n' % (i, fmt_tree(tree[i])))
            body.append('def kl_%d : List (List Comp) := %s%s\n'
                        % (i, ' ++ ('.join('kl_%d_%d' % (i, k) for k in range(m)), ')' * (m - 1)))
            body.append('theorem cellw_%d : walkK tree_%d (rootMs 4 %d) (List.replicate 4 3) kl_%d = some [] := by\n'
                        '  decide +kernel\n' % (i, i, i, i))
            pf = 'cellv_%d_%d' % (i, m - 1)
            for k in range(m - 2, -1, -1):
                pf = 'allP_app cellv_%d_%d (%s)' % (i, k, pf)
            body.append('theorem cellv_%d : allP %s kl_%d :=\n  %s\n\n' % (i, PRED, i, pf))
        head = ['import Bohr59aCoreK.Walk\n', 'import Bohr59aK5C.Help\n'] + ['import Bohr59aK5C.%s\n' % p for p in sorted(need)]
        head.append('open Bohr59aK Bohr59aCore Bohr59aK5H\n' + OPTS)
        path = os.path.join(cdir, name + '.lean')
        open(path + '.part', 'w').write(''.join(head + body)); os.replace(path + '.part', path)
        cstats.append(dict(module=name, imports=len(need), keys=sum(len(c[0]) for i in range(ci * per_c, min(len(tree), (ci + 1) * per_c)) for c in cells[i])))
    st = dict(k=K, n0=N0, nverts=len(verts), vertex_modules=len(vmods), cell_modules=ncmod, per_v=per_v, per_c=per_c,
              leaf_key_refs=used_total, max_cell_imports=max(c['imports'] for c in cstats), version=2, chunk=chunk,
              pbudget=pbudget, chunk_modules=len(pmods), chunks=sum(len(c) for c in cells),
              max_chunk_imports=max(p['imports'] for p in pstats), max_cell_module_keys=max(c['keys'] for c in cstats),
              json_sha256=hashlib.sha256(open(os.path.join(frozen, 'bb5_t2187.json'), 'rb').read()).hexdigest())
    json.dump(st, open(os.path.join(out, 'stats', 'K5K.json'), 'w'), indent=1)
    print(json.dumps(st))


main()
