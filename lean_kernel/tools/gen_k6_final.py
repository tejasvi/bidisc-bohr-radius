#!/usr/bin/env python3
"""Write the Mathlib-side glue of the K6 proof (hints as data): Bohr59aK6G/Gxxx.lean (512 modules: the cell property of
root cells 64 j .. 64 j + 63 from cellw6_i / cellv6_i of Bohr59aK6C/Cxxx via Bohr59a.CertK.cellOK_of_K2h, per-leaf key lists) and
Bohr59aK6G/Final.lean (S_6 <= 2.363 kernel-only; with Bohr59aK.sidon5K the kernel-only K2Claim).  Cell theorem names
assumed: cellw6_<i> : walkK2 tree6_<i> (rootMs 5 <i>) (List.replicate 5 3) kls6_<i> = some [],
cellv6_<i> : allP (allP (fun key => ∃ Y Wr x, vertexOKKh trigTT 6 2363 1000 key Y Wr x = true)) kls6_<i>.
usage: gen_k6_final.py OUT_DIR"""
import os, sys
out = sys.argv[1]
NC, PER = 8 ** 5, 64
NM = NC // PER
os.makedirs(os.path.join(out, 'Bohr59aK6G'), exist_ok=True)
B = '((2363 : ℕ) : ℝ) / ((1000 : ℕ) : ℝ)'
for j in range(NM):
    lo, hi = PER * j, PER * j + PER
    lines = [f'import Bohr59aK6C.C{j:03d}\n', 'import Bohr59a.CertK\n\n',
             f'/-! Glue: the cell property of the root cells {lo}..{hi - 1} (generated by tools/gen_k6_final.py). -/\n\n',
             'open Bohr59a.CertK Bohr59a.Cert Bohr59aK\n', 'set_option maxHeartbeats 0\n\n', 'namespace Bohr59aK6G\n\n',
             f'theorem cells_{j} : ∀ i, {lo} ≤ i → i < {hi} → CellOK 5 ({B}) i := by\n',
             '  intro i h1 h2\n', '  interval_cases i\n']
    lines += [f'  · exact cellOK_of_K2h rfl (by norm_num) cellw6_{i} cellv6_{i}\n' for i in range(lo, hi)]
    lines.append('\nend Bohr59aK6G\n')
    open(os.path.join(out, 'Bohr59aK6G', f'G{j:03d}.lean'), 'w').write(''.join(lines))
# dispatch in two levels (512 glue modules): 8 blocks of 64 glue theorems
fin = [f'import Bohr59aK6G.G{j:03d}\n' for j in range(NM)] + ['import Bohr59aK5G.Final\n', 'import Bohr59a.FinalV3\n\n']
fin += ['/-!\n# `K₂ ≥ 0.301657`, K version (kernel only)\n\n',
        '`S({0..6}) ≤ 2.363` from the kernel checks of the k = 6 certificate (hints as data), with `Bohr59aK.sidon5K`, then\n',
        '`Bohr59a.K2_ge_of_sidon`.  Generated by tools/gen_k6_final.py.\n-/\n\n',
        'open Bohr59a Bohr59a.Cert Bohr59a.CertK\n', 'set_option maxHeartbeats 0\n\n', 'namespace Bohr59aK\n\n']
for b in range(NM // 64):
    fin += [f'theorem cells6_block_{b} : ∀ i, {4096 * b} ≤ i → i < {4096 * (b + 1)} → CellOK 5 ({B}) i := by\n',
            '  intro i h1 h2\n',
            f'  obtain ⟨j, r, hr, rfl⟩ : ∃ j r, r < 64 ∧ i = 64 * j + r := ⟨i / 64, i % 64, Nat.mod_lt _ (by norm_num),\n',
            '    (Nat.div_add_mod i 64).symm⟩\n',
            f'  have hj1 : {64 * b} ≤ j := by omega\n', f'  have hj2 : j < {64 * (b + 1)} := by omega\n',
            '  interval_cases j\n']
    fin += [f'  · exact Bohr59aK6G.cells_{j} _ (by omega) (by omega)\n' for j in range(64 * b, 64 * (b + 1))]
    fin.append('\n')
fin += [f'theorem cells6_all : ∀ i < {NC}, CellOK 5 ({B}) i := by\n', '  intro i hi\n',
        '  obtain ⟨b, r, hr, rfl⟩ : ∃ b r, r < 4096 ∧ i = 4096 * b + r := ⟨i / 4096, i % 4096, Nat.mod_lt _ (by norm_num),\n',
        '    (Nat.div_add_mod i 4096).symm⟩\n', '  have hb : b < 8 := by omega\n', '  interval_cases b\n']
fin += [f'  · exact cells6_block_{b} _ (by omega) (by omega)\n' for b in range(NM // 64)]
fin += ['\n/-- `S({0..6}) ≤ 2.363`, kernel only -/\n',
        'theorem sidon6K : SidonBound 6 (2363 / 1000) := by\n',
        f'  have h : SidonBound (5 + 1) ({B}) := sidon_of_cells cells6_all\n',
        '  norm_num at h ⊢\n', '  exact h\n\n',
        '/-- **`K₂ ≥ 0.301657`** (kernel only), given Patel\'s colligation estimate. -/\n',
        'theorem K2_ge_K (hPC : PatelColligation) : K2Claim := K2_ge_of_sidon hPC sidon5K sidon6K\n\n',
        'end Bohr59aK\n']
open(os.path.join(out, 'Bohr59aK6G', 'Final.lean'), 'w').write(''.join(fin))
print('wrote', NM, 'glue modules + Final')
