#!/usr/bin/env python3
"""Write the Mathlib-side glue of the K5 proof: Bohr59aK5G/Gxx.lean (64 modules: the cell property of root cells
64 j .. 64 j + 63 from cellw_i / cellv_i of Bohr59aK5C/Cxx via Bohr59a.CertK.cellOK_of_K) and Bohr59aK5G/Final.lean
(S_5 <= 2.187 kernel-only, then Bohr59aK.K2_ge_K5).  usage: gen_k5_final.py OUT_DIR [FORMAT]   (FORMAT 1: walkK / cellOK_of_K; 2 (default): per-leaf walkK2 / cellOK_of_K2)"""
import os, sys
out = sys.argv[1]
FMT = int(sys.argv[2]) if len(sys.argv) > 2 else 2
LEMMA = 'cellOK_of_K2' if FMT == 2 else 'cellOK_of_K'
NC, PER = 4096, 64
os.makedirs(os.path.join(out, 'Bohr59aK5G'), exist_ok=True)
B = '((2187 : ℕ) : ℝ) / ((1000 : ℕ) : ℝ)'
for j in range(NC // PER):
    lo, hi = PER * j, PER * j + PER
    lines = [f'import Bohr59aK5C.C{j:02d}\n', 'import Bohr59a.CertK\n\n',
             f'/-! Glue: the cell property of the root cells {lo}..{hi - 1} (generated by tools/gen_k5_final.py). -/\n\n',
             'open Bohr59a.CertK Bohr59a.Cert Bohr59aK\n', 'set_option maxHeartbeats 0\n\n', 'namespace Bohr59aK5G\n\n',
             f'theorem cells_{j} : ∀ i, {lo} ≤ i → i < {hi} → CellOK 4 ({B}) i := by\n',
             '  intro i h1 h2\n', '  interval_cases i\n']
    lines += [f'  · exact {LEMMA} rfl (by norm_num) cellw_{i} cellv_{i}\n' for i in range(lo, hi)]
    lines.append('\nend Bohr59aK5G\n')
    open(os.path.join(out, 'Bohr59aK5G', f'G{j:02d}.lean'), 'w').write(''.join(lines))
fin = [f'import Bohr59aK5G.G{j:02d}\n' for j in range(NC // PER)] + ['import Bohr59a.FinalV2b\n\n']
fin += ['/-!\n# `K₂ ≥ 0.301633`, K version (kernel only)\n\n',
        '`S({0..5}) ≤ 2.187` from the kernel checks of the k = 5 certificate (vertex theorems `v_*`, walk theorems `cellw_*`,\n',
        'linking theorems `cellv_*`), through `Bohr59a.CertK.cellOK_of_K` and `Bohr59a.Cert.sidon_of_cells`, then\n',
        '`Bohr59a.K2_ge_of_sidon5`.  Generated by tools/gen_k5_final.py.\n-/\n\n',
        'open Bohr59a Bohr59a.Cert Bohr59a.CertK\n', 'set_option maxHeartbeats 0\n\n', 'namespace Bohr59aK\n\n',
        f'theorem cells_all : ∀ i < 4096, CellOK 4 ({B}) i := by\n',
        '  intro i hi\n',
        '  obtain ⟨j, r, hr, rfl⟩ : ∃ j r, r < 64 ∧ i = 64 * j + r := ⟨i / 64, i % 64, Nat.mod_lt _ (by norm_num),\n',
        '    (Nat.div_add_mod i 64).symm⟩\n',
        '  have hj : j < 64 := by omega\n',
        '  interval_cases j\n']
fin += [f'  · exact Bohr59aK5G.cells_{j} _ (by omega) (by omega)\n' for j in range(NC // PER)]
fin += ['\n/-- `S({0..5}) ≤ 2.187`, kernel only -/\n',
        'theorem sidon5K : SidonBound 5 (2187 / 1000) := by\n',
        f'  have h : SidonBound (4 + 1) ({B}) := sidon_of_cells cells_all\n',
        '  norm_num at h ⊢\n', '  exact h\n\n',
        '/-- **`K₂ ≥ 0.301633`** (kernel only), given Patel\'s colligation estimate. -/\n',
        'theorem K2_ge_K5 (hPC : PatelColligation) : (301633 / 1000000 : ℝ) ≤ K2 := K2_ge_of_sidon5 hPC sidon5K\n\n',
        'end Bohr59aK\n']
open(os.path.join(out, 'Bohr59aK5G', 'Final.lean'), 'w').write(''.join(fin))
print('wrote', NC // PER, 'glue modules + Final')
