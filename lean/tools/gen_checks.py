#!/usr/bin/env python3
"""Write the shard check modules (Bohr59aCheck/<NAME>.lean: `shard`, `ok := by native_decide`) and the decoding test modules
(Bohr59aTest/<NAME>.lean: `stats := by native_decide`, against the exporter's stats/<NAME>.json) for the exported shards.

usage: gen_checks.py PROJECT_DIR NAME [NAME ...]      (NAME = K5 or K6S00 ... K6S47)
"""
import json, os, sys

if sys.flags.optimize:
    sys.exit('refusing to run with python -O')

BOUND = {5: (2187, 1000), 6: (2363, 1000)}


def lean_list(pairs):
    return '[' + ', '.join('(%d, %d)' % (a, b) for a, b in pairs) + ']'


def main():
    proj = sys.argv[1]
    for name in sys.argv[2:]:
        st = json.load(open(os.path.join(proj, 'stats', name + '.json')))
        k, n0, nsh, s = st['k'], st['n0'], st['nsh'], st['s']
        bnum, bden = BOUND[k]
        hdr = 'decodeShard %d %d %d %d %d %d Bohr59aData.%s.data' % (k, n0, nsh, s, bnum, bden, name)
        os.makedirs(os.path.join(proj, 'Bohr59aCheck'), exist_ok=True)
        os.makedirs(os.path.join(proj, 'Bohr59aTest'), exist_ok=True)
        with open(os.path.join(proj, 'Bohr59aCheck', name + '.lean'), 'w') as f:
            f.write('import Bohr59aCore.Check\nimport Bohr59aCore.Decode\nimport Bohr59aData.%s\n\n' % name)
            f.write('/-! Generated by tools/gen_checks.py: the certificate check of shard %s (k = %d, s = %d of %d). -/\n\n'
                    % (name, k, s, nsh))
            f.write('namespace Bohr59aCheck.%s\nopen Bohr59aCore\n\n' % name)
            f.write('/-- the shard (header fields pinned; cells and certificates decoded from the stream) -/\n')
            f.write('def shard : Shard := %s\n\n' % hdr)
            f.write('theorem ok : checkShard shard = true := by native_decide\n\n')
            f.write('end Bohr59aCheck.%s\n' % name)
        key = [(m, j) for (_tan, m, j) in st['first_vertex_key']]
        y = [(a, b) for a, b in st['first_vertex_y']]
        with open(os.path.join(proj, 'Bohr59aTest', name + '.lean'), 'w') as f:
            f.write('import Bohr59aCore.Decode\nimport Bohr59aData.%s\n\n' % name)
            f.write('/-! Generated by tools/gen_checks.py: decoding cross-check of shard %s against the exporter. -/\n\n' % name)
            f.write('namespace Bohr59aTest.%s\nopen Bohr59aCore\n\n' % name)
            f.write('theorem stats : shardStats (%s) =\n    (%d, %d, %d, %s,\n     %s) := by\n  native_decide\n\n'
                    % (hdr, st['ncells'], st['nverts'], st['leaves'], lean_list(key), lean_list(y)))
            f.write('end Bohr59aTest.%s\n' % name)
        print('wrote', name)


main()
