#!/usr/bin/env python3
"""Write Bohr59aN/Final.lean: K_2 >= 0.301657 (N version) from the 49 shard checks (Bohr59aCheck.K5, K6S00..K6S47)
and the soundness theorems Bohr59a.Cert.sidon_of_shard / sidon_of_shards.  usage: gen_final_n.py OUT_FILE"""
import sys
N = 48
names = [f'K6S{s:02d}' for s in range(N)]
imports = '\n'.join(['import Bohr59a.FinalV3', 'import Bohr59a.CertShard', 'import Bohr59aCheck.K5'] +
                    [f'import Bohr59aCheck.{n}' for n in names])
cases = '\n'.join([f'  | {s} => Bohr59aCheck.{n}.shard' for s, n in enumerate(names[:-1])] +
                  [f'  | _ => Bohr59aCheck.{names[-1]}.shard'])
oks = ', '.join(f'Bohr59aCheck.{n}.ok' for n in names)
src = f'''{imports}

/-!
# `K₂ ≥ 0.301657`, N version

The Sidon bounds `S({{0..5}}) ≤ 2.187` and `S({{0..6}}) ≤ 2.363` from the certificate checks `checkShard shard = true`
(`Bohr59aCheck.*`, by `native_decide`: one shard for `k = 5`, 48 shards `s = 0, …, 47` for `k = 6`), through the soundness
theorems `Bohr59a.Cert.sidon_of_shard` / `sidon_of_shards`, and then `Bohr59a.K2_ge_of_sidon`.  Generated by
tools/gen_final_n.py.
-/

namespace Bohr59aN

open Bohr59a Bohr59a.Cert Bohr59aCore

/-- `S({{0..5}}) ≤ 2.187` -/
theorem sidon5 : SidonBound 5 (2187 / 1000) := by
  have h : SidonBound 5 ((mkRat 2187 1000 : ℚ) : ℝ) := sidon_of_shard Bohr59aCheck.K5.ok rfl rfl
  rwa [Rat.cast_mkRat_of_ne_zero _ (by norm_num), show ((2187 : ℤ) : ℝ) = 2187 by norm_num,
    show ((1000 : ℕ) : ℝ) = 1000 by norm_num] at h

/-- the 48 shards of `k = 6` -/
def k6shards (s : Fin {N}) : Shard :=
  match s.val with
{cases}

lemma k6_k : ∀ s, (k6shards s).k = 6 := by intro s; fin_cases s <;> rfl
lemma k6_nsh : ∀ s, (k6shards s).nsh = {N} := by intro s; fin_cases s <;> rfl
lemma k6_s : ∀ s, (k6shards s).s = s.val := by intro s; fin_cases s <;> rfl
lemma k6_bnum : ∀ s, (k6shards s).bnum = 2363 := by intro s; fin_cases s <;> rfl
lemma k6_bden : ∀ s, (k6shards s).bden = 1000 := by intro s; fin_cases s <;> rfl
lemma k6_ok : ∀ s, checkShard (k6shards s) = true := by
  intro s
  fin_cases s
  exacts [{oks}]

/-- `S({{0..6}}) ≤ 2.363` -/
theorem sidon6 : SidonBound 6 (2363 / 1000) := by
  have h : SidonBound 6 ((mkRat 2363 1000 : ℚ) : ℝ) :=
    sidon_of_shards k6shards (by norm_num) k6_k k6_nsh k6_s k6_bnum k6_bden k6_ok
  rwa [Rat.cast_mkRat_of_ne_zero _ (by norm_num), show ((2363 : ℤ) : ℝ) = 2363 by norm_num,
    show ((1000 : ℕ) : ℝ) = 1000 by norm_num] at h

/-- **`K₂ ≥ 0.301657`** (N version), given Patel's colligation estimate. -/
theorem K2_ge_N (hPC : PatelColligation) : K2Claim := K2_ge_of_sidon hPC sidon5 sidon6

end Bohr59aN
'''
open(sys.argv[1], 'w').write(src)
print('wrote', sys.argv[1])
