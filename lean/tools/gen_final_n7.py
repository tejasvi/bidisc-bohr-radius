#!/usr/bin/env python3
"""Write Bohr59aN7/Final.lean: K_2 >= 0.301665 (N version) from the 576 half-domain shard checks of the k = 7 certificate
(Bohr59aCheck.K7S000..K7S575, `checkShardH shard = true` by native_decide) through Bohr59a.Cert.sidon_of_shardsH, with
S_5 and S_6 from the N package (Bohr59aN.sidon5, Bohr59aN.sidon6) and Bohr59a.K2_ge_of_sidon7 (Bohr59a/FinalV3b.lean).
The layout follows tools/gen_final_n.py.  usage: gen_final_n7.py OUT_FILE"""
import sys
N = 576
names = [f'K7S{s:03d}' for s in range(N)]
imports = '\n'.join(['import Bohr59a.FinalV3b', 'import Bohr59a.CertHalf', 'import Bohr59aN.Final'] +
                    [f'import Bohr59aCheck.{n}' for n in names])
cases = '\n'.join([f'  | {s} => Bohr59aCheck.{n}.shard' for s, n in enumerate(names[:-1])] +
                  [f'  | _ => Bohr59aCheck.{names[-1]}.shard'])
oks = ', '.join(f'Bohr59aCheck.{n}.ok' for n in names)
src = f'''{imports}

/-!
# `K₂ ≥ 0.301665`, N version

The Sidon bound `S({{0..7}}) ≤ 2.552` from the half-domain certificate checks `checkShardH shard = true` (`Bohr59aCheck.K7S*`,
by `native_decide`, 576 shards `s = 0, …, 575` of the root cells of `[0, 1] × [-1, 1]^5`), through the soundness theorem
`Bohr59a.Cert.sidon_of_shardsH` (conjugation covers the other half); `S_5`, `S_6` from `Bohr59aN`; then
`Bohr59a.K2_ge_of_sidon7`.  Generated by tools/gen_final_n7.py.
-/

namespace Bohr59aN7

open Bohr59a Bohr59a.Cert Bohr59aCore
set_option maxRecDepth 100000

/-- the 576 half-domain shards of `k = 7` -/
def k7shards (s : Fin {N}) : Shard :=
  match s.val with
{cases}

lemma k7_k : ∀ s, (k7shards s).k = 7 := by intro s; fin_cases s <;> rfl
lemma k7_nsh : ∀ s, (k7shards s).nsh = {N} := by intro s; fin_cases s <;> rfl
lemma k7_s : ∀ s, (k7shards s).s = s.val := by intro s; fin_cases s <;> rfl
lemma k7_bnum : ∀ s, (k7shards s).bnum = 2552 := by intro s; fin_cases s <;> rfl
lemma k7_bden : ∀ s, (k7shards s).bden = 1000 := by intro s; fin_cases s <;> rfl
lemma k7_ok : ∀ s, checkShardH (k7shards s) = true := by
  intro s
  fin_cases s
  exacts [{oks}]

/-- `S({{0..7}}) ≤ 2.552` -/
theorem sidon7 : SidonBound 7 (2552 / 1000) := by
  have h : SidonBound 7 ((mkRat 2552 1000 : ℚ) : ℝ) :=
    sidon_of_shardsH k7shards (by norm_num) k7_k k7_nsh k7_s k7_bnum k7_bden k7_ok
  rwa [Rat.cast_mkRat_of_ne_zero _ (by norm_num), show ((2552 : ℤ) : ℝ) = 2552 by norm_num,
    show ((1000 : ℕ) : ℝ) = 1000 by norm_num] at h

/-- **`K₂ ≥ 0.301665`** (N version), given Patel's colligation estimate. -/
theorem K2_ge_N7 (hPC : PatelColligation) : (60333 / 200000 : ℝ) ≤ K2 :=
  K2_ge_of_sidon7 hPC Bohr59aN.sidon5 Bohr59aN.sidon6 sidon7

end Bohr59aN7
'''
open(sys.argv[1], 'w').write(src)
print('wrote', sys.argv[1])
