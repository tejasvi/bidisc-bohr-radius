#!/usr/bin/env python3
"""Export the frozen v3 Sidon certificates (bb5_t2187.json, bb6/sh*.json) to Lean data modules (untrusted encoding).

Each data module `Bohr59aData/<NAME>.lean` holds one base64 string literal `data` (no imports); `Bohr59aCore/Decode.lean`
decodes it.  Binary layout (all integers little-endian):

  magic  b"B59A" | u8 version (1) | u8 k | u8 n0 | u8 D | u32 ncells | u32 nverts
  trees  ncells trees in increasing root index, preorder bytes: 0 = leaf, d + 1 = split coordinate d (lo subtree, hi subtree)
  verts  nverts records: D components (u16 m + 32768, u8 tan * 128 + j), then 2k float64 bit patterns
         (re y_1, im y_1, ..., re y_k, im y_k)

Key components: ['c', q] -> (tan 0, m = 512 q, j = 0); ['t', q, h] -> (tan 1, m = 512 q, j = log2(1/h)).  The exporter refuses
any q with 512 q not an integer, any h not a power of 1/2 in (0, 1/4], any non-finite float, and (k = 6) any shard whose root
indices are not exactly {i < n0^D : i % nshards = shard}.

usage: export59.py k5 FROZEN_DIR OUT_DIR
       export59.py k6 FROZEN_DIR OUT_DIR S [S ...]
writes OUT_DIR/Bohr59aData/<NAME>.lean and OUT_DIR/stats/<NAME>.json (counts, blob sha256, decode spot checks).
"""
import base64, hashlib, json, math, os, struct, sys
from fractions import Fraction

if sys.flags.optimize:
    sys.exit('refusing to run with python -O')


def die(msg):
    sys.exit('EXPORT FAILED: ' + msg)


def enc_tree(node, D, out, depth=0):
    if depth > 400:
        die('tree too deep')
    if node == 'L':
        out.append(0)
    elif isinstance(node, list) and len(node) == 4 and node[0] == 'S' and isinstance(node[1], int) and 0 <= node[1] < D:
        out.append(node[1] + 1)
        enc_tree(node[2], D, out, depth + 1)
        enc_tree(node[3], D, out, depth + 1)
    else:
        die('bad tree node ' + str(node)[:60])


def enc_comp(kk):
    if isinstance(kk, list) and len(kk) == 2 and kk[0] == 'c':
        q = Fraction(kk[1]); tan, j = 0, 0
    elif isinstance(kk, list) and len(kk) == 3 and kk[0] == 't':
        q, h = Fraction(kk[1]), Fraction(kk[2]); tan = 1
        if not (0 < h <= Fraction(1, 4)) or h.numerator != 1 or h.denominator & (h.denominator - 1):
            die('tangent half-width not a power of 1/2 in (0, 1/4]: ' + str(kk))
        j = h.denominator.bit_length() - 1
    else:
        die('bad key component ' + str(kk))
    m = q * 512
    if m.denominator != 1 or not (-32768 <= m.numerator < 32768) or j > 127:
        die('key component out of range ' + str(kk))
    return struct.pack('<HB', m.numerator + 32768, tan * 128 + j), (tan == 1, m.numerator, j)


def export(k, n0, cells, verts, name, outdir, extra):
    D = k - 1
    tb = bytearray()
    for _, tree in cells:
        enc_tree(tree, D, tb)
    vb = bytearray()
    first = None
    for ent in verts:
        if not (isinstance(ent, list) and len(ent) == 2 and isinstance(ent[0], list) and len(ent[0]) == D
                and isinstance(ent[1], list) and len(ent[1]) == 2 * k):
            die('bad vertex entry')
        key = []
        for kk in ent[0]:
            b, c = enc_comp(kk)
            vb += b; key.append(c)
        for x in ent[1]:
            if not (isinstance(x, float) and math.isfinite(x)):
                die('non-finite or non-float y')
            vb += struct.pack('<d', x)
        if first is None:
            first = (key, [Fraction(x) for x in ent[1]])
    head = b'B59A' + struct.pack('<BBBBII', 1, k, n0, D, len(cells), len(verts))
    blob = bytes(head) + bytes(tb) + bytes(vb)
    b64 = base64.b64encode(blob).decode('ascii')
    ns = 'Bohr59aData.' + name
    os.makedirs(os.path.join(outdir, 'Bohr59aData'), exist_ok=True)
    os.makedirs(os.path.join(outdir, 'stats'), exist_ok=True)
    path = os.path.join(outdir, 'Bohr59aData', name + '.lean')
    with open(path + '.part', 'w') as f:
        f.write('/-! Generated by tools/export59.py from the frozen v3 certificates (untrusted encoding, see Bohr59aCore/Decode.lean). -/\n')
        f.write('namespace ' + ns + '\n\n')
        f.write('/-- base64 of the binary shard stream -/\n')
        f.write('def data : String := "' + b64 + '"\n\n')
        f.write('end ' + ns + '\n')
    os.replace(path + '.part', path)
    st = dict(name=name, k=k, n0=n0, D=D, ncells=len(cells), nverts=len(verts), tree_bytes=len(tb), blob_bytes=len(blob),
              b64_chars=len(b64), blob_sha256=hashlib.sha256(blob).hexdigest(),
              lean_sha256=hashlib.sha256(open(path, 'rb').read()).hexdigest(),
              tree_sum=sum(tb), leaves=tb.count(0), first_vertex_key=[list(c) for c in first[0]] if first else None,
              first_vertex_y=[[x.numerator, x.denominator] for x in first[1]] if first else None, **extra)
    with open(os.path.join(outdir, 'stats', name + '.json'), 'w') as f:
        json.dump(st, f, indent=1)
    print(name, 'cells', len(cells), 'verts', len(verts), 'blob', len(blob), 'sha', st['blob_sha256'][:12], flush=True)


def main():
    mode, frozen, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
    if mode == 'k5':
        cert = json.load(open(os.path.join(frozen, 'bb5_t2187.json')))
        k, n0, tree = cert['k'], cert['n0'], cert['tree']
        if not (k == 5 and n0 == 8 and len(tree) == n0 ** (k - 1)):
            die('unexpected k5 header')
        export(k, n0, list(enumerate(tree)), cert['verts'], 'K5', outdir, dict(nsh=1, s=0, target=cert.get('target')))
    elif mode == 'k6':
        for s in [int(a) for a in sys.argv[4:]]:
            cert = json.load(open(os.path.join(frozen, 'bb6', 'sh%d.json' % s)))
            k, n0, nsh = cert['k'], cert['n0'], cert['nshards']
            if not (k == 6 and n0 == 8 and nsh == 48 and cert['shard'] == s and 'tree' not in cert):
                die('unexpected k6 header in shard %d' % s)
            idx = sorted(int(i) for i in cert['cells'])
            if idx != list(range(s, n0 ** (k - 1), nsh)) or len(cert['cells']) != len(idx):
                die('shard %d root indices are not {i : i %% %d == %d}' % (s, nsh, s))
            cells = [(i, cert['cells'][str(i)]) for i in idx]
            export(k, n0, cells, cert['verts'], 'K6S%02d' % s, outdir, dict(nsh=nsh, s=s, target=cert.get('target')))
    else:
        die('mode must be k5 or k6')


main()
